def glyph_rows(char):
    """The seven rows of a glyph, falling back to a blank for unknowns."""
    return GLYPHS.get(char, GLYPHS[" "])


def text_width(s, scale):
    """Pixel width of string s rendered at the given scale."""
    return len(s) * 6 * scale
