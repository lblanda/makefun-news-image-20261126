CELL_W = 5
CELL_H = 7
ADVANCE = 6  # one blank column between glyphs


def glyph_for(ch):
    """Return the 7-row bitmap for a character, blank for unknown ones."""
    return GLYPHS.get(ch, GLYPHS[" "])


def text_width(text, scale=1):
    """Pixel width of text at the given scale, without trailing space."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def text_height(scale=1):
    return CELL_H * scale


def draw_text(canvas, width, x, y, text, color, scale=1):
    """Stamp text onto a flat RGB bytearray canvas of the given width.

    canvas is a bytearray of 3 bytes per pixel; color is an (r, g, b)
    tuple. Characters that fall off the right edge are clipped.
    """
    r, g, b = color
    for ch in text:
        rows = glyph_for(ch.upper())
        for row_i, row in enumerate(rows):
            for col_i, cell in enumerate(row):
                if cell != "#":
                    continue
                px = x + col_i * scale
                py = y + row_i * scale
                for dy in range(scale):
                    yy = py + dy
                    if yy < 0:
                        continue
                    for dx in range(scale):
                        xx = px + dx
                        if xx < 0 or xx >= width:
                            continue
                        o = (yy * width + xx) * 3
                        if o < 0 or o + 3 > len(canvas):
                            continue
                        canvas[o] = r
                        canvas[o + 1] = g
                        canvas[o + 2] = b
        x += ADVANCE * scale


def draw_text_centered(canvas, width, cx, y, text, color, scale=1):
    draw_text(canvas, width, cx - text_width(text, scale) // 2, y, text, color, scale)


def wrap_lines(text, max_width, scale=1):
    """Greedy word wrap; returns a list of lines fitting max_width."""
    words = text.split(" ")
    lines = []
    current = ""
    for word in words:
        trial = word if not current else current + " " + word
        if text_width(trial, scale) <= max_width or not current:
            current = trial
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines
